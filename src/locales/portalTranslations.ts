export function getPortalTranslation(locale: string | undefined, key: string): string {
  const norm = (locale === 'ck' ? 'ckb' : locale) as 'en' | 'ar' | 'zh' | 'ckb';
  const validLocale = portalTranslations[norm] ? norm : 'en';
  const val = portalTranslations[validLocale][key];
  if (val !== undefined) return val;
  return portalTranslations.en[key] || key;
}

