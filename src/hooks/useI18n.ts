/**
 * Localized date formatter conforming to strict locale rules
 */
export function formatLocalizedDate(dateInput: string | Date | number, lang: Locale = 'en', style: 'long' | 'short' = 'long'): string {
  try {
    const d = typeof dateInput === 'string' || typeof dateInput === 'number' ? new Date(dateInput) : dateInput;
    if (isNaN(d.getTime())) return '';

    const day = d.getDate();
    const monthIndex = d.getMonth();
    const year = d.getFullYear();

    if (lang === 'ckb') {
      const monthName = kurdishMonths[monthIndex];
      return `${day}ی ${monthName}ی ${year}`;
    }

    if (lang === 'ar') {
      const monthName = arabicMonths[monthIndex];
      return `${day} ${monthName} ${year}`;
    }

    if (lang === 'zh') {
      return `${year}年${monthIndex + 1}月${day}日`;
    }

    return d.toLocaleDateString('en-US', {
      year: 'numeric',
      month: style === 'long' ? 'long' : 'short',
      day: 'numeric'
    });
  } catch (e) {
    return String(dateInput);
  }
}

/**
 * Localized large billion currency value formatter
 */
export function formatCurrencyBillion(amountInBillions: number, lang: Locale = 'en'): string {
  if (lang === 'ckb') {
    return `${amountInBillions} ملیار دۆلار`;
  }
  if (lang === 'ar') {
    return `${amountInBillions} مليار دولار`;
  }
  if (lang === 'zh') {
    return `${amountInBillions * 10}亿美元`;
  }
  return `$${amountInBillions}B`;
}

/**
 * Localized percentage formatter
 */
export function formatLocalizedPercent(value: number, lang: Locale = 'en'): string {
  if (lang === 'ckb' || lang === 'ar') {
    return `٪${value}`;
  }
  return `${value}%`;
}

export function useI18n(lang: Locale) {
  return {
    t: (key: string) => {
      if (key.startsWith('newsroom.')) {
        return getNewsroomTranslation(lang, key);
      }
      return (dict[lang] as any)?.[key] || (dict['en'] as any)?.[key] || key;
    },
    formatDate: (d: string | Date | number, style: 'long' | 'short' = 'long') => formatLocalizedDate(d, lang, style),
    formatBillion: (amt: number) => formatCurrencyBillion(amt, lang),
    formatPercent: (val: number) => formatLocalizedPercent(val, lang)
  };
}

